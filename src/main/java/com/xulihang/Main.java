package com.xulihang;

import com.xulihang.psd.Psd;
import com.xulihang.psd.TextLayer;
import com.xulihang.psd.TextOrientation;

import java.awt.Color;
import java.awt.GradientPaint;
import java.awt.Graphics2D;
import java.awt.RenderingHints;
import java.awt.image.BufferedImage;
import java.nio.file.Path;
import java.nio.file.Paths;

public class Main {
    public static void main(String[] args) throws Exception {
        int width = 800;
        int height = 600;

        Psd psd = new Psd(width, height);
        psd.addImageLayer("Background", createBackground(width, height), 0, 0);
        psd.addImageLayer("Accent", createAccent(), 60, 60);

        TextLayer title = new TextLayer("Title", "Hello PSD\n你好，Photoshop！", 100, 240)
                .setFontFamily("Microsoft YaHei")
                .setFontName("MicrosoftYaHei")
                .setFontSize(56)
                .setBold(true)
                .setColor(new Color(0x1f2937))
                .setBox(600, 220)
                .setLineHeight(72);

        TextLayer vertical = new TextLayer("Vertical", "春眠不觉晓\n处处闻啼鸟", 700, 120)
                .setFontFamily("SimSun")
                .setFontName("SimSun")
                .setFontSize(40)
                .setColor(new Color(0x1f2937))
                .setOrientation(TextOrientation.VERTICAL);

        TextLayer note = new TextLayer("Note", "Editable text layer generated by psd4j.", 100, 480)
                .setFontFamily("Segoe UI")
                .setFontName("SegoeUI")
                .setFontSize(22)
                .setColor(new Color(0x374151));

        psd.addTextLayer(title);
        psd.addTextLayer(vertical);
        psd.addTextLayer(note);

        Path output = Paths.get(args.length > 0 ? args[0] : "output.psd");
        psd.write(output);
        System.out.println("Wrote " + output.toAbsolutePath());
    }

    private static BufferedImage createBackground(int width, int height) {
        BufferedImage image = new BufferedImage(width, height, BufferedImage.TYPE_INT_RGB);
        Graphics2D graphics = image.createGraphics();
        graphics.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
        graphics.setPaint(new GradientPaint(0, 0, new Color(0xe0f2fe), width, height, new Color(0xbfdbfe)));
        graphics.fillRect(0, 0, width, height);

        graphics.setColor(new Color(0x38bdf8, true));
        graphics.fillOval(520, -60, 360, 360);
        graphics.setColor(new Color(0x818cf8, true));
        graphics.fillOval(-120, 380, 320, 320);
        graphics.dispose();
        return image;
    }

    private static BufferedImage createAccent() {
        BufferedImage image = new BufferedImage(220, 140, BufferedImage.TYPE_INT_ARGB);
        Graphics2D graphics = image.createGraphics();
        graphics.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
        graphics.setColor(new Color(255, 255, 255, 170));
        graphics.fillRoundRect(0, 0, 220, 140, 32, 32);
        graphics.setColor(new Color(0x0ea5e9));
        graphics.fillRoundRect(24, 24, 172, 10, 5, 5);
        graphics.dispose();
        return image;
    }
}
